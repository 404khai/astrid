// Builds Astrid's live canvas (web/canvas.html, ADR 0036) and voice ring
// (web/voice.html) into one HTML file each for the phone app's WebViews (ADR
// 0039): web/vite.phone.config.ts makes one script and one stylesheet with
// fonts inlined, and this folds both into the page. Output:
// modules/astrid-overlay/android/src/main/assets/astrid-{canvas,voice}.html.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "../../web");
const assets = join(here, "../modules/astrid-overlay/android/src/main/assets");

// The live canvas and the voice ring, each folded into one file.
for (const page of ["canvas", "voice", "blobs"]) {
  execFileSync("npx", ["vite", "build", "-c", "vite.phone.config.ts", "--logLevel", "warn"], {
    cwd: web,
    stdio: "inherit",
    env: { ...process.env, PHONE_PAGE: page },
  });
  const dist = join(web, "dist-phone");
  let html = readFileSync(join(dist, `${page}.html`), "utf8");
  const files = readdirSync(join(dist, "assets"));
  const script = files.filter((f) => f.endsWith(".js"));
  const style = files.filter((f) => f.endsWith(".css"));
  if (script.length !== 1 || style.length > 1) throw new Error(`expected one script and at most one stylesheet, got ${files.join(", ")}`);

  // Function replacers: the bundle contains `$&`-like sequences.
  html = html.replace(/<script type="module"[^>]*src="[^"]+"[^>]*><\/script>/, () => {
    const code = readFileSync(join(dist, "assets", script[0]), "utf8").replace(/<\/script/gi, "<\\/script");
    return `<script type="module">${code}</script>`;
  });
  html = html.replace(/<link rel="stylesheet"[^>]*href="[^"]+"[^>]*>/, () =>
    style.length ? `<style>${readFileSync(join(dist, "assets", style[0]), "utf8")}</style>` : "",
  );
  html = html.replace(/<link rel="icon"[^>]*>/, "");
  if (/(src|href)="\.\/assets\//.test(html)) throw new Error("an asset was left out of the page");

  const out = join(assets, `astrid-${page}.html`);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, html);
  console.log(`${page}: ${(html.length / 1024).toFixed(0)} KiB -> ${out}`);
}

// The built-in blobs (repo `blobs/`, AGPL-3.0; see its README) for the phone's
// sidebar row, as a generated module.
const blobs = join(here, "../../blobs");
const items = readdirSync(blobs)
  .filter((f) => f.endsWith(".avatar.json"))
  .sort()
  .map((f) => ({ id: f, ...JSON.parse(readFileSync(join(blobs, f), "utf8")) }))
  .map(({ id, ...character }) => ({ id, name: character.name ?? id, character }));
writeFileSync(
  join(here, "../src/phone/blobs.generated.ts"),
  `// Generated by scripts/build-canvas.mjs from blobs/ (AGPL-3.0). Do not edit.\nexport const builtInBlobs = ${JSON.stringify(items)} as const;\n`,
);
console.log(`blobs: ${items.length} characters -> src/phone/blobs.generated.ts`);
